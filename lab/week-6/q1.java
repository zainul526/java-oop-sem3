 class q1{
    //1. Write a Java program to print the odd numbers from 1 to 99.

    public static void main(String[] args){
        for(int i=1; i<=99; i+=2){
            {
                if(i!=99)
                {System.out.print(i+", ");}
                else
                    {System.out.print(i);}
            }
        }
    }
}
